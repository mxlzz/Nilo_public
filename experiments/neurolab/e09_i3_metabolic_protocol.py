"""E09.02i-I3: preregistered N-line metabolic-precursor learning benchmark.

DO NOT infer C1 fidelity from these measurements. Every chemical half-life
is a LAB RATE=40, not a value read from the original genome. Feedback is
generated by an external evaluator AFTER a target action and injected as
raw substrates. No correct target/action is an input to the neural modules.

Compare M metabolic plastic brain, F identical chemistry + frozen dendrites,
C original direct-feedback brain (non-matched reference), Q privileged
tabular baseline (causal provenance). Negative outcomes remain data.
"""
from __future__ import annotations

from dataclasses import asdict, replace
from pathlib import Path
import argparse
import json
import statistics

from .c1_context_brain import C1ContextBrain
from .c1_reaction_inspector import Reaction
from .e09_coupled_brain import CoupledState, initial_coupled, coupled_tick
from .e09_pool_decay import decay_pool
from .e09_historical_receptor import Receptor
from .e09_context_protocol import MAPPING_A, MAPPING_B, ZERO
from .e09_delayed_distractors_protocol import (
    trials, neural_phase, train_tabular_q, holdout_tabular_q,
)

SEEDS=tuple(range(200,220))
DELAYS=(1,2,3)
TRAIN_REPEATS=10
HOLDOUT_REPEATS=6
TARGET_TICKS=4
LAB_RATE=40
PRECURSOR_DOSE=80
RATES=(LAB_RATE,)*256
MODES=("M","F","C","Q")
ROOT=Path(__file__).resolve().parents[2]


def selected_genes() -> tuple[tuple[Receptor,...],tuple[Reaction,...]]:
    recdata=json.loads((ROOT/"docs/neurolab/resultados/e09h3_receptores_genoma_original.json").read_text(encoding="utf-8"))
    rxdata=json.loads((ROOT/"docs/neurolab/resultados/e09h2_reacciones_genoma_original.json").read_text(encoding="utf-8"))
    if recdata["receptor_count"]!=43 or rxdata["reaction_count"]!=58:
        raise AssertionError("different genotype record")
    receptors=tuple(Receptor(int(i),**value)
                    for i,value in recdata["brain_receptors"].items())
    def reaction(index):
        g=rxdata["sample_original_genes"][str(index)]
        return Reaction(index,0,*[g[k] for k in (
            "qa","ca","qb","cb","qc","cc","qd","cd","rate"
        )])
    return receptors,tuple(reaction(i) for i in (57,71,111,112))


def add_environment_precursors(
    state: CoupledState, *, correct: bool, dose: int = PRECURSOR_DOSE,
) -> CoupledState:
    """External evaluator writes substrates, not a neuron or a target ID."""
    if not isinstance(state,CoupledState) or type(correct) is not bool:
        raise TypeError("coupled state and boolean outcome required")
    if type(dose) is not int or not 0<=dose<=255:
        raise ValueError("chemical dose must be a byte")
    changes=((33,dose),(1,dose)) if correct else ((17,dose),)
    values=list(state.chemistry.pool)
    for chem,added in changes:
        values[chem]=min(255,values[chem]+added)
    return CoupledState(
        state.brain,replace(state.chemistry,pool=tuple(values))
    )


def metabolic_step(
    brain:C1ContextBrain,
    state:CoupledState,
    context:int,
    receptors:tuple[Receptor,...],
    reactions:tuple[Reaction,...],
    *,
    plasticity:bool,
):
    """Brain-before-chemistry; C1 pool decay after reactions, rate40 lab."""
    prior=state.chemistry.tick
    tr=coupled_tick(brain,state,context,(),receptors,reactions,learn=plasticity)
    pool_after=decay_pool(tr.after.chemistry.pool,RATES,prior)
    after=CoupledState(
        tr.after.brain,replace(tr.after.chemistry,pool=pool_after),
    )
    return after,tr.brain_trace.action,tr


def metabolic_phase(
    brain:C1ContextBrain,
    state:CoupledState,
    sequence:tuple[tuple[int,int],...],
    mapping:tuple[str,str],
    receptors:tuple[Receptor,...],
    reactions:tuple[Reaction,...],
    *,
    feedback:bool,
    plasticity:bool,
):
    """Score fourth choice and deliver at distractor arrival as preregistered."""
    correct={d:0 for d in DELAYS}
    totals={d:0 for d in DELAYS}
    by_context=[0,0]
    counts=[0,0]
    missing=0
    deliveries=0
    chemical_ticks=0
    saturation_ticks=0
    peaks={str(c):0 for c in (49,50,51)}
    for target,delay in sequence:
        action=None
        for _ in range(TARGET_TICKS):
            state,action,_=metabolic_step(
                brain,state,target,receptors,reactions,plasticity=plasticity
            )
            chemical_ticks+=1
        correct_choice=int(action==mapping[target])
        correct[delay]+=correct_choice
        totals[delay]+=1
        by_context[target]+=correct_choice
        counts[target]+=1
        missing+=int(action is None)
        for _ in range(delay):
            state,_,_=metabolic_step(
                brain,state,1-target,receptors,reactions,plasticity=plasticity
            )
            chemical_ticks+=1
        if feedback and action is not None:
            state=add_environment_precursors(
                state,correct=bool(correct_choice)
            )
            deliveries+=1
        state,_,_=metabolic_step(
            brain,state,1-target,receptors,reactions,plasticity=plasticity
        )
        chemical_ticks+=1
        for c in (49,50,51):
            peaks[str(c)]=max(peaks[str(c)],state.chemistry.pool[c])
        saturation_ticks+=int(any(state.chemistry.pool[c]==255
                                  for c in (49,50,51)))
    if len(sequence)==0:
        raise ValueError("nonempty trial sequence required")
    return state,{
        "overall":sum(correct.values())/len(sequence),
        "by_delay":{str(d):correct[d]/totals[d] for d in DELAYS},
        "by_context":[by_context[i]/counts[i] for i in (0,1)],
        "target_choices":len(sequence),
        "target_missing":missing,
        "delivered_precursor_events":deliveries,
        "chemical_ticks":chemical_ticks,
        "pool_peaks":peaks,
        "saturation_on_final_tick_count":saturation_ticks,
    }


def run_seed(seed:int) -> dict:
    if type(seed) is not int or seed<0:
        raise ValueError("seed must be nonnegative")
    receptors,reactions=selected_genes()
    brains={mode:C1ContextBrain(seed) for mode in ("M","F","C")}
    states={
        "M":initial_coupled(brains["M"],receptors),
        "F":initial_coupled(brains["F"],receptors),
        "C":brains["C"].initial(),
    }
    frozen_at_start=states["F"].brain.dendrites
    table=[[0.0,0.0],[0.0,0.0]]
    q_tick=0
    answer={}
    for phase,salt_train,salt_test,mapping in (
        ("first",50000,70000,MAPPING_A),
        ("reversed",60000,80000,MAPPING_B),
    ):
        train=trials(seed,salt_train,TRAIN_REPEATS)
        holdout=trials(seed,salt_test,HOLDOUT_REPEATS)
        training={}
        evaluated={}
        for mode in ("M","F"):
            state,info=metabolic_phase(
                brains[mode],states[mode],train,mapping,receptors,reactions,
                feedback=True,plasticity=(mode=="M"),
            )
            states[mode]=state
            training[mode]=info
            if mode=="F" and state.brain.dendrites!=frozen_at_start:
                raise AssertionError("frozen synapses changed")
            _,evaluated[mode]=metabolic_phase(
                brains[mode],state,holdout,mapping,receptors,reactions,
                feedback=False,plasticity=False,
            )
        states["C"],infoC=neural_phase(
            brains["C"],states["C"],train,mapping,"C",learn=True
        )
        training["C"]=infoC
        _,evaluated["C"]=neural_phase(
            brains["C"],states["C"],holdout,mapping,"C",learn=False
        )
        table,q_tick,q_train=train_tabular_q(
            table,train,mapping,seed=seed,choice_tick=q_tick,
        )
        training["Q"]={"updates":q_train["updates"]}
        evaluated["Q"]=holdout_tabular_q(
            table,holdout,mapping,seed=seed,choice_tick=q_tick,
        )
        answer[phase]={
            "holdout":evaluated,
            "training":training,
            "training_trials":len(train),
            "holdout_trials":len(holdout),
        }
    if states["F"].brain.dendrites != frozen_at_start:
        raise AssertionError("frozen dendrite invariant failed")
    return {"seed":seed,**answer}


def run_all(seeds:tuple[int,...]=SEEDS) -> dict:
    if not isinstance(seeds,tuple) or not seeds or any(
            type(s) is not int or s<0 for s in seeds):
        raise ValueError("nonempty deterministic seed tuple required")
    rows=[run_seed(seed) for seed in seeds]
    means={
        phase:{mode:statistics.mean(
            row[phase]["holdout"][mode]["overall"] for row in rows)
            for mode in MODES}
        for phase in ("first","reversed")
    }
    by_delay={
        phase:{mode:{str(d):statistics.mean(
            row[phase]["holdout"][mode]["by_delay"][str(d)] for row in rows
        ) for d in DELAYS} for mode in MODES}
        for phase in ("first","reversed")
    }
    joint={
        mode:sum(row["first"]["holdout"][mode]["overall"]>=.90 and
                 row["reversed"]["holdout"][mode]["overall"]>=.90
                 for row in rows)
        for mode in MODES
    }
    advantage_m_vs_f=sum(
        means[phase]["M"]-means[phase]["F"] for phase in means
    )/2
    gate=(
        joint["M"]>=18
        and all(means[phase]["M"]>=.85 for phase in means)
        and all(by_delay[phase]["M"][str(d)]>=.70
                for phase in by_delay for d in DELAYS)
        and advantage_m_vs_f>=.15
    )
    return {
        "protocol":"E09_02I_I3_BENCHMARK_PRE_REGISTRO-v1",
        "seeds":list(seeds),
        "lab_rate_per_chemical":LAB_RATE,
        "precursor_dose":PRECURSOR_DOSE,
        "reactions":[57,71,111,112],
        "n_units":6,"dendrites":8,
        "mean_holdout_target_accuracy":means,
        "mean_by_delay":by_delay,
        "joint_ge_0_90":joint,
        "mean_M_minus_F_all_phases":advantage_m_vs_f,
        "gate_M_exploratory":gate if len(seeds)==20 else None,
        "per_seed":rows,
        "limitations":(
            "All rates40 are synthetic; chemical genotype half-lives unknown; "
            "C direct pulses mismatched in timing/amplitude; Q privileged; "
            "no automatic brain-emitter source binding; no G05 causal proof"
        ),
    }


def main() -> None:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output",type=Path)
    args=parser.parse_args()
    record=json.dumps(run_all(),indent=2,sort_keys=True)+"\n"
    if args.output:
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(record,encoding="utf-8")
    print(record,end="")


if __name__=="__main__":
    main()
